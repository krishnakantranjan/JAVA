package Collection;

import java.util.*;

public class Maps {
    static void main(String[] args) {

        Map<Integer, String> map = new HashMap<>();

        map.put(101, "Krishna");
        map.put(102, "Aditya");
        map.put(103, "Rohit");


        System.out.println(map.containsKey(101)); // true
        System.out.println(map.get(102)); // Aditya





    }
}
